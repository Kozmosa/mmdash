function renderGoStruct(name, schema, schemas) {
  const required = new Set(schema.required ?? []);
  const properties = Object.entries(schema.properties ?? {});
  const fields = properties.map(([jsonName, property]) => {
    const isRequired = required.has(jsonName);
    return {
      goName: goName(jsonName),
      goType: goType(property, isRequired, schemas),
      isRequired,
      jsonName,
      property,
    };
  });
  const declarations = fields
    .map(
      (field) =>
        `\t${field.goName} ${field.goType} \`json:"${field.jsonName}${field.isRequired ? "" : ",omitempty"}"\``,
    )
    .join("\n");
  const validations = [];
  if ((schema.minProperties ?? 0) > 0) {
    const optionalChecks = fields
      .filter((field) => !field.isRequired)
      .map((field) => `request.${field.goName} == nil`);
    if (optionalChecks.length > 0) {
      validations.push(
        `\tif ${optionalChecks.join(" && ")} {\n\t\treturn fmt.Errorf("at least one field is required")\n\t}`,
      );
    }
  }
  for (const [triggerName, dependencyNames] of Object.entries(
    schema.dependentRequired ?? {},
  )) {
    const trigger = fields.find((field) => field.jsonName === triggerName);
    if (!trigger) {
      throw new Error(
        `${name} dependentRequired references unknown field ${triggerName}`,
      );
    }
    for (const dependencyName of dependencyNames) {
      const dependency = fields.find(
        (field) => field.jsonName === dependencyName,
      );
      if (!dependency) {
        throw new Error(
          `${name} dependentRequired references unknown field ${dependencyName}`,
        );
      }
      if (dependency.isRequired) continue;
      const triggerPresent = trigger.isRequired
        ? "true"
        : `request.${trigger.goName} != nil`;
      validations.push(
        `\tif ${triggerPresent} && request.${dependency.goName} == nil {\n\t\treturn fmt.Errorf("${dependencyName} is required when ${triggerName} is present")\n\t}`,
      );
    }
  }
  for (const field of fields) {
    validations.push(...goValidation(field, schemas));
  }
  return `// ${name} is generated from the Core request-body schema.
type ${name} struct {
${declarations}
}

// Validate applies the OpenAPI field constraints before a handler runs.
func (request ${name}) Validate() error {
${validations.length > 0 ? validations.join("\n") : "\treturn nil"}
${validations.length > 0 ? "\treturn nil" : ""}
}`;
}

function goType(schema, required, schemas) {
  const resolved = resolveSchema(schema, schemas);
  let value;
  switch (resolved.type) {
    case "string":
      value = resolved.format === "date-time" ? "time.Time" : "string";
      break;
    case "boolean":
      value = "bool";
      break;
    case "integer":
      value = "int64";
      break;
    case "number":
      value = "float64";
      break;
    case "array":
      value = `[]${goType(resolved.items ?? {}, true, schemas)}`;
      break;
    case "object":
      value = "map[string]interface{}";
      break;
    default:
      value = "interface{}";
  }
  return required ? value : `*${value}`;
}

function goValidation(field, schemas) {
  const schema = resolveSchema(field.property, schemas);
  const prefix = field.isRequired
    ? `request.${field.goName}`
    : `*request.${field.goName}`;
  const lines = [];
  const conditions = [];
  if (field.isRequired) {
    if (schema.type === "string" && schema.format !== "date-time") {
      conditions.push(
        `if ${prefix} == "" {\n\t\treturn fmt.Errorf("${field.jsonName} is required")\n\t}`,
      );
    } else if (schema.type === "object" || schema.type === "array") {
      conditions.push(
        `if ${prefix} == nil {\n\t\treturn fmt.Errorf("${field.jsonName} is required")\n\t}`,
      );
    } else if (schema.type === "string" && schema.format === "date-time") {
      conditions.push(
        `if ${prefix}.IsZero() {\n\t\treturn fmt.Errorf("${field.jsonName} is required")\n\t}`,
      );
    }
  }
  if (schema.type === "string" && Number.isInteger(schema.minLength)) {
    conditions.push(
      `if len(${prefix}) < ${schema.minLength} {\n\t\treturn fmt.Errorf("${field.jsonName} is too short")\n\t}`,
    );
  }
  if (schema.type === "string" && Number.isInteger(schema.maxLength)) {
    conditions.push(
      `if len(${prefix}) > ${schema.maxLength} {\n\t\treturn fmt.Errorf("${field.jsonName} is too long")\n\t}`,
    );
  }
  if (schema.type === "string" && schema.format === "email") {
    conditions.push(
      `if parsed, err := mail.ParseAddress(${prefix}); err != nil || parsed.Address != ${prefix} {\n\t\treturn fmt.Errorf("${field.jsonName} must be an email address")\n\t}`,
    );
  }
  if (schema.type === "string" && schema.const !== undefined) {
    conditions.push(
      `if ${prefix} != ${JSON.stringify(schema.const)} {\n\t\treturn fmt.Errorf("${field.jsonName} has an unsupported value")\n\t}`,
    );
  }
  if (schema.type === "string" && typeof schema.pattern === "string") {
    conditions.push(
      `if matched, err := regexp.MatchString(${JSON.stringify(schema.pattern)}, ${prefix}); err != nil || !matched {\n\t\treturn fmt.Errorf("${field.jsonName} has an invalid format")\n\t}`,
    );
  }
  const enumeration = schema.enum;
  if (Array.isArray(enumeration) && enumeration.length > 0) {
    const allowed = enumeration
      .map((value) => `${prefix} != ${JSON.stringify(value)}`)
      .join(" && ");
    conditions.push(
      `if ${allowed} {\n\t\treturn fmt.Errorf("${field.jsonName} has an unsupported value")\n\t}`,
    );
  }
  if (
    (schema.type === "integer" || schema.type === "number") &&
    typeof schema.minimum === "number"
  ) {
    conditions.push(
      `if ${prefix} < ${schema.minimum} {\n\t\treturn fmt.Errorf("${field.jsonName} is below its minimum")\n\t}`,
    );
  }
  if (
    (schema.type === "integer" || schema.type === "number") &&
    typeof schema.maximum === "number"
  ) {
    conditions.push(
      `if ${prefix} > ${schema.maximum} {\n\t\treturn fmt.Errorf("${field.jsonName} exceeds its maximum")\n\t}`,
    );
  }
  if (schema.type === "array" && Number.isInteger(schema.maxItems)) {
    conditions.push(
      `if len(${prefix}) > ${schema.maxItems} {\n\t\treturn fmt.Errorf("${field.jsonName} has too many items")\n\t}`,
    );
  }
  if (schema.type === "array" && Number.isInteger(schema.minItems)) {
    conditions.push(
      `if len(${prefix}) < ${schema.minItems} {\n\t\treturn fmt.Errorf("${field.jsonName} has too few items")\n\t}`,
    );
  }
  if (!field.isRequired && conditions.length > 0) {
    lines.push(
      `\tif request.${field.goName} != nil {\n${conditions
        .map((condition) => indent(condition, 2))
        .join("\n")}\n\t}`,
    );
  } else {
    lines.push(...conditions.map((condition) => indent(condition, 1)));
  }
  return lines;
}

function renderTypeScriptDTOs(common, event) {
  const definitions = common.$defs ?? {};
  for (const required of [
    "Identifier",
    "Timestamp",
    "RequestId",
    "Error",
    "CursorPage",
    "Actor",
  ]) {
    if (!definitions[required]) {
      throw new Error(`Common DTO schema is missing $defs.${required}`);
    }
  }
  for (const field of event.required ?? []) {
    if (!(field in (event.properties ?? {}))) {
      throw new Error(`Event envelope required field ${field} is undefined`);
    }
  }
  return `// Code generated by scripts/generate-contracts.mjs; DO NOT EDIT.
// Sources: contracts/json-schema/common/dtos.schema.json,
//          contracts/events/event-envelope.schema.json

export type Identifier = string;
export type Timestamp = string;
export type RequestId = string;
export type Actor = Record<string, string>;

export type ApiError = {
  code: string;
  details?: unknown;
  message: string;
  request_id?: RequestId;
};

export type CursorPage = {
  has_more: boolean;
  next_cursor?: string | null;
};

export type EventEnvelope<
  TPayload extends Record<string, unknown> = Record<string, unknown>,
> = {
  actor: Actor | null;
  causation_id: string | null;
  correlation_id: string | null;
  event_id: string;
  event_type: string;
  occurred_at: Timestamp;
  payload: TPayload;
  producer: string;
  project_id: string | null;
  schema_version: number;
};
`;
}

function renderGoEventEnvelope(event) {
  const required = new Set(event.required ?? []);
  for (const field of [
    "event_id",
    "event_type",
    "schema_version",
    "occurred_at",
    "producer",
    "project_id",
    "actor",
    "correlation_id",
    "causation_id",
    "payload",
  ]) {
    if (!required.has(field) || !event.properties?.[field]) {
      throw new Error(`Event envelope is missing required field ${field}`);
    }
  }
  const source = `// Code generated by scripts/generate-contracts.mjs; DO NOT EDIT.
// Source: contracts/events/event-envelope.schema.json

package generated

import (
\t"fmt"
\t"regexp"
\t"time"
)

var (
\teventIDPattern = regexp.MustCompile(\`^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$\`)
\teventTypePattern = regexp.MustCompile(\`^[a-z][a-z0-9_]*(\\.[a-z][a-z0-9_]*)+$\`)
)

// EventEnvelope is the stable cross-process event transport.
type EventEnvelope struct {
\tActor map[string]string \`json:"actor"\`
\tCausationID *string \`json:"causation_id"\`
\tCorrelationID *string \`json:"correlation_id"\`
\tEventID string \`json:"event_id"\`
\tEventType string \`json:"event_type"\`
\tOccurredAt time.Time \`json:"occurred_at"\`
\tPayload map[string]interface{} \`json:"payload"\`
\tProducer string \`json:"producer"\`
\tProjectID *string \`json:"project_id"\`
\tSchemaVersion int64 \`json:"schema_version"\`
}

// Validate applies the Event Envelope JSON Schema invariants.
func (event EventEnvelope) Validate() error {
\tif !eventIDPattern.MatchString(event.EventID) {
\t\treturn fmt.Errorf("event_id must be a UUID")
\t}
\tif !eventTypePattern.MatchString(event.EventType) {
\t\treturn fmt.Errorf("event_type is invalid")
\t}
\tif event.SchemaVersion < 1 {
\t\treturn fmt.Errorf("schema_version must be positive")
\t}
\tif event.OccurredAt.IsZero() {
\t\treturn fmt.Errorf("occurred_at is required")
\t}
\tif event.Producer == "" {
\t\treturn fmt.Errorf("producer is required")
\t}
\tif event.Payload == nil {
\t\treturn fmt.Errorf("payload is required")
\t}
\treturn nil
}
`;
  const formatted = spawnSync("gofmt", [], {
    encoding: "utf8",
    input: source,
  });
  if (formatted.status !== 0) {
    throw new Error(`gofmt generated event envelope: ${formatted.stderr}`);
  }
  return normalizeNewlines(formatted.stdout);
}

function resolveSchema(schema, schemas) {
  if (!schema?.$ref) {
    return schema ?? {};
  }
  const name = schema.$ref.split("/").at(-1);
  return schemas[name] ?? {};
}

function goName(value) {
  return value
    .split(/[_-]/)
    .map((part) => {
      if (part === "id") return "ID";
      if (part === "ids") return "IDs";
      if (part === "api") return "API";
      if (part === "url") return "URL";
      return part.charAt(0).toUpperCase() + part.slice(1);
    })
    .join("");
}

function indent(value, levels) {
  const prefix = "\t".repeat(levels);
  return value
    .split("\n")
    .map((line) => `${prefix}${line}`)
    .join("\n");
}

async function readJSON(relativePath) {
  return JSON.parse(await readFile(path.join(root, relativePath), "utf8"));
}

async function readYAML(relativePath) {
  return yaml.load(await readFile(path.join(root, relativePath), "utf8"));
}

function normalizeNewlines(value) {
  return value.replace(/\r\n/g, "\n");
}
