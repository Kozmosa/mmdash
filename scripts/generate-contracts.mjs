import { spawnSync } from "node:child_process";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import yaml from "js-yaml";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const checkOnly = process.argv.includes("--check");

const [openAPI, commonSchema, eventSchema] = await Promise.all([
  readYAML("contracts/openapi/core.yaml"),
  readJSON("contracts/json-schema/common/dtos.schema.json"),
  readJSON("contracts/events/event-envelope.schema.json"),
]);

const outputs = new Map([
  [
    "backend/internal/contract/generated/handler_types.go",
    renderGoHandlerTypes(openAPI),
  ],
  [
    "backend/internal/contract/generated/event_envelope.go",
    renderGoEventEnvelope(eventSchema),
  ],
  [
    "packages/api-types/src/generated.ts",
    renderTypeScriptDTOs(commonSchema, eventSchema),
  ],
]);

let changed = false;
for (const [relativePath, content] of outputs) {
  const absolutePath = path.join(root, relativePath);
  if (checkOnly) {
    const existing = await readFile(absolutePath, "utf8").catch(() => "");
    if (normalizeNewlines(existing) !== normalizeNewlines(content)) {
      console.error(`${relativePath} is stale; run pnpm contracts:generate.`);
      changed = true;
    }
    continue;
  }
  await mkdir(path.dirname(absolutePath), { recursive: true });
  await writeFile(absolutePath, content, "utf8");
  console.log(`generated ${relativePath}`);
}

if (changed) {
  process.exit(1);
}

